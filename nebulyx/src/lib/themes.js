export const THEME_MAP = Object.fromEntries(THEMES.map((t) => [t.id, t]));

export function defineThemes(monaco) {
  THEMES.forEach((t) => {
    const { id, ...data } = t.def;
    monaco.editor.defineTheme(id, data);
  });
}

